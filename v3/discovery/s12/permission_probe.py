"""DEVELOPMENT screen of the binary-source permission compiler.

Codex (GPT-6). Graph reachability is compared with explicit truth assignments.
No solver, population model or native numerical dependency is used.
"""
from itertools import product, combinations
from pathlib import Path
import hashlib
import json
import platform
import random
import sys
import time

HERE = Path(__file__).resolve().parent


def lit_true(lit, world):
    return ((world >> (lit//2)) & 1) == (lit & 1)


def holds(clauses, world):
    return all(any(lit_true(lit, world) for lit in clause) for clause in clauses)


def graph(n, clauses):
    reach = [1 << lit for lit in range(2*n)]
    for clause in clauses:
        a, b = (clause[0], clause[0]) if len(clause)==1 else clause
        reach[a^1] |= 1 << b
        reach[b^1] |= 1 << a
    for k in range(2*n):
        for i in range(2*n):
            if (reach[i] >> k) & 1:
                reach[i] |= reach[k]
    satisfiable = not any((reach[2*i] >> (2*i+1)) & 1 and
                          (reach[2*i+1] >> (2*i)) & 1 for i in range(n))
    forced = sum(1 << lit for lit in range(2*n)
                 if (reach[lit^1] >> lit) & 1)
    return satisfiable, reach, forced


def contradictory(n, bits):
    return any((bits >> (2*i)) & 3 == 3 for i in range(n))


def add_units(reach, forced, units):
    for lit in units:
        forced |= reach[lit]
    return forced


def projections(n, target, reach, forced):
    result = []
    for clause in target:
        variables = tuple(sorted({lit//2 for lit in clause}))
        patterns = []
        for bits in product([0,1], repeat=len(variables)):
            units = [2*i+b for i,b in zip(variables,bits)]
            if not contradictory(n, add_units(reach, forced, units)):
                patterns.append(bits)
        result.append((variables,patterns))
    return result


def filtered_projection(variables, patterns, forced):
    return [bits for bits in patterns if all(
        not ((forced >> (2*i+(1-b))) & 1) for i,b in zip(variables,bits))]


def compile_masks(target, cached, forced):
    result = []
    for clause,(variables,patterns) in zip(target,cached):
        false_bit = {lit//2: 1-(lit&1) for lit in clause}
        for bits in filtered_projection(variables,patterns,forced):
            forbidden = [b^false_bit[i] for i,b in zip(variables,bits)]
            result.append(tuple(2*i+(1-b) for i,b in zip(variables,forbidden)))
    return result


def implication_characterization(n, edges, worlds, receipt, mask):
    """DAG-only characterization, independently from compiled mask clauses."""
    source = [x for x in worlds if all(lit_true(l,x) for l in receipt)]
    assert source
    status = []
    for i in range(n):
        possible = {(x>>i)&1 for x in source}
        status.append(next(iter(possible)) if len(possible)==1 else None)
    for u,v in edges:
        a,b = status[u],status[v]
        du,dv = (mask>>u)&1,(mask>>v)&1
        if a is None and b is None and (du or dv):
            return False
        if a==0 and b is None and du:
            return False
        if a is None and b==1 and dv:
            return False
        if a is not None and b is not None and (a^du) > (b^dv):
            return False
    return True


def main():
    begun=time.perf_counter_ns()
    rng=random.Random(120018)
    totals=dict(formulas=0, satisfiable=0, receipts=0, contradictory_receipts=0,
                pair_projections=0, mask_comparisons=0, implication_comparisons=0)
    examples=[]
    for trial in range(180):
        n=2+trial%4
        pool=[(lit,) for lit in range(2*n)]
        pool += [(2*i+a,2*j+b) for i,j in combinations(range(n),2)
                 for a,b in product([0,1],repeat=2)]
        source=rng.sample(pool,rng.randint(0,min(len(pool),2*n+2)))
        target=rng.sample(pool,rng.randint(0,min(len(pool),n+3)))
        worlds=[x for x in range(1<<n) if holds(source,x)]
        satisfiable,reach,forced=graph(n,source)
        assert satisfiable == bool(worlds)
        totals["formulas"]+=1
        if not worlds:
            continue
        totals["satisfiable"]+=1
        cached=projections(n,target,reach,forced)
        # Every partial receipt, not merely those generated by one query order.
        for values in product([-1,0,1],repeat=n):
            receipt=[2*i+b for i,b in enumerate(values) if b!=-1]
            compatible=[x for x in worlds if all(lit_true(l,x) for l in receipt)]
            current=add_units(reach,forced,receipt)
            assert contradictory(n,current) == (not compatible)
            if not compatible:
                totals["contradictory_receipts"]+=1
                continue
            totals["receipts"]+=1
            for variables,patterns in cached:
                expected={tuple((x>>i)&1 for i in variables) for x in compatible}
                actual=set(filtered_projection(variables,patterns,current))
                assert actual==expected,(trial,source,target,receipt,variables,actual,expected)
                totals["pair_projections"]+=1
            mask_formula=compile_masks(target,cached,current)
            allowed=[]
            for mask in range(1<<n):
                expected=all(holds(target,x^mask) for x in compatible)
                actual=holds(mask_formula,mask)
                assert actual==expected,(trial,source,target,receipt,mask)
                totals["mask_comparisons"]+=1
                if actual:
                    allowed.append(mask)
            if trial<8 and len(receipt)<=1:
                examples.append(dict(trial=trial,n=n,source=source,target=target,
                                     receipt=receipt,worlds=len(compatible),allowed=allowed))
    for trial in range(32):
        n=2+trial%4
        edges=[(i,j) for i,j in combinations(range(n),2) if rng.random()<.4]
        clauses=[(2*u,2*v+1) for u,v in edges]
        worlds=[x for x in range(1<<n) if holds(clauses,x)]
        for values in product([-1,0,1],repeat=n):
            receipt=[2*i+b for i,b in enumerate(values) if b!=-1]
            compatible=[x for x in worlds if all(lit_true(l,x) for l in receipt)]
            if not compatible:
                continue
            for mask in range(1<<n):
                expected=all(holds(clauses,x^mask) for x in compatible)
                actual=implication_characterization(n,edges,worlds,receipt,mask)
                assert actual==expected,(edges,receipt,mask)
                totals["implication_comparisons"]+=1
    # The Horn width-three obstruction, outside the graph compiler contract.
    source=[(0,2,5)]  # not-u OR not-v OR z
    target=[(0,3)]    # u => v
    before=[x for x in range(8) if holds(source,x)]
    after=[x for x in before if lit_true(4,x)]
    before_pairs={tuple((x>>i)&1 for i in [0,1]) for x in before}
    after_pairs={tuple((x>>i)&1 for i in [0,1]) for x in after}
    assert before_pairs==set(product([0,1],repeat=2))
    assert after_pairs=={(0,0),(0,1),(1,0)}
    assert all(holds(target,x^2) for x in after)
    assert not any(all(holds(target,x^d) for x in before) for d in range(8))
    result=dict(contributor="Codex (GPT-6)",status="DEVELOPMENT",seed=120018,
        python=sys.version,platform=platform.platform(),
        source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        elapsed_ns=time.perf_counter_ns()-begun,totals=totals,examples=examples,
        horn_obstruction=dict(source=source,target=target,receipt=[4],
                              before_pairs=sorted(before_pairs),after_pairs=sorted(after_pairs),
                              enabled_mask=2),
        limitations="Finite small-world screen; no priority, general proof, runtime superiority or complete service cost claim")
    (HERE/"permission_probe.json").write_bytes((json.dumps(result,indent=2)+"\n").encode())
    print(json.dumps({k:result[k] for k in ["status","totals","elapsed_ns"]}))


if __name__=="__main__":
    main()
